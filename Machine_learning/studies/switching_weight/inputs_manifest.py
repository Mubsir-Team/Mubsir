"""
Lists every file OUTSIDE this study folder that the study's scripts read (read-only), with its SHA-256, and checks it
against hashes_before.json where that file was covered by the baseline. Writes INPUTS.md and results/inputs_manifest.json.
Nothing outside study_switching_weight/ is written by any script of the study.
"""

import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODEL_DIR = HERE.parent.parent  # studies/<name>/ -> Model/ (moved 2026-11-26)
ROOT = MODEL_DIR.parent

INPUTS = [  # (path relative to the project root, read by, role)
    ("Model/data/model_dataset_995.parquet", "train (via 05_tune.load; dev rows only)", "100 MUBSIR features"),
    ("Model/work/labels.parquet", "train (via 05_tune.load)", "y_10 labels"),
    ("Model/work/eval_meta.parquet", "train (via 05_tune.load)", "per-row evaluation context"),
    ("Model/work/oof/lightgbm_h10.parquet", "train (gate G1)", "Stage A OOF (reproduction check)"),
    ("Model/config/final_split.csv", "train (via 05_tune.load)", "dev/test split (dev users only)"),
    ("Model/config/cv_folds.csv", "train, analyze", "existing 5x3 grouped CV folds"),
    ("Model/config/user_meta.csv", "train, analyze", "attacker flag and strata (evaluation only)"),
    ("Model/config/selection_rules.json", "train (hash check in 05_tune.load)", "registered selection rules"),
    ("Model/config/training_predictor_allowlist.csv", "train (via common.feature_list)", "frozen allowlist"),
    ("Model/pipeline/common.py", "train", "frozen helpers (imported, not modified)"),
    ("Model/pipeline/models.py", "train", "LightGBM constructor and defaults (_lgbm, MAX_TREES, ES_ROUNDS)"),
    ("Model/pipeline/metrics.py", "analyze", "threshold_at_fpr"),
    ("Model/pipeline/05_tune.py", "train", "frozen loader"),
    ("Model/studies/controlled_rotation/data/counterfactual_cases.parquet", "train", "existing matched cases (P2), read-only"),
    ("Model/studies/switching_baseline/results/habit_2010_dev_users.csv", "analyze", "2010 habit (descriptive benign-alarm table only)"),
]
NOT_READ = ["Model/work/test/test_scores.parquet and every test-set score or decision (model_dataset_995.parquet is opened whole by the frozen loader, and test users' rows are dropped immediately, before any computation)",
            "the frozen model, calibration and thresholds", "every data-generation or injection input"]


def digest(p):
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


before = json.loads((HERE / "hashes_before.json").read_text(encoding="utf-8"))
rows = []
for rel, by, role in INPUTS:
    p = ROOT / rel
    sha = digest(p)
    key = rel[len("Model/"):] if rel.startswith("Model/") else None
    base = before.get(key) if key else None
    status = ("unchanged vs hashes_before.json" if base == sha else "CHANGED" if base else
              "outside the hash baseline (read-only; hash recorded here)")
    rows.append(dict(path=rel, read_by=by, role=role, sha256=sha, bytes=p.stat().st_size, baseline=status))
(HERE / "results" / "inputs_manifest.json").write_text(json.dumps(rows, indent=1), encoding="utf-8")
assert not any(r["baseline"] == "CHANGED" for r in rows), "an input changed during the study"

md = ["# External inputs (read-only)", "",
      "Every file outside `study_switching_weight/` that a script of this study reads. None is written. Generated by",
      "`inputs_manifest.py`; SHA-256 values are also in `results/inputs_manifest.json`.", "",
      "| File | Read by | Role | SHA-256 (first 16) | Baseline check |", "|---|---|---|---|---|"]
md += [f"| `{r['path']}` | {r['read_by']} | {r['role']} | `{r['sha256'][:16]}` | {r['baseline']} |" for r in rows]
md += ["", "**Never read:** " + "; ".join(NOT_READ) + ".", "",
       "Python modules of `Model/pipeline/` are imported in place with byte-code writing disabled",
       "(`PYTHONDONTWRITEBYTECODE=1` in `run_all.ps1`), so no `__pycache__` is created in frozen folders."]
(HERE / "INPUTS.md").write_text("\n".join(md) + "\n", encoding="utf-8")
print(f"{len(rows)} inputs hashed; changed: 0")
