"""
Write INPUTS.md and results/inputs_manifest.json: every file outside studies/learning_curve/ that a script of this study
reads, with SHA-256. None of them is written. The test set is not among them.
"""

import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODEL_DIR = HERE.parent.parent
INPUTS = [
    ("pipeline/common.py", "train, analyze", "paths, seed, feature list"),
    ("pipeline/models.py", "train", "Stage A LightGBM configuration (_lgbm, MAX_TREES, ES_ROUNDS)"),
    ("pipeline/metrics.py", "analyze", "threshold_at_fpr"),
    ("pipeline/05_tune.py", "train", "load() and rows(): dev data, folds, user metadata"),
    ("config/cv_folds.csv", "train, analyze", "Stage A folds (fit / es / valid)"),
    ("config/user_meta.csv", "train, analyze", "stratum, schedule group, attacker flag, scenario properties"),
    ("config/final_split.csv", "train (via 05_tune.load)", "dev users only"),
    ("config/selection_rules.json", "train (via 05_tune.load)", "hash check of the registered rules"),
    ("config/training_predictor_allowlist.csv", "train (via common.feature_list)", "the 97 kept predictors"),
    ("config/engineered_features.csv", "train (via common.feature_list)", "the 3 engineered predictors"),
    ("data/model_dataset_995.parquet", "train (via 05_tune.load)", "features; only dev rows are used"),
    ("work/labels.parquet", "train (via 05_tune.load)", "y_10"),
    ("work/eval_meta.parquet", "train (via 05_tune.load)", "in_window flag"),
    ("work/oof/lightgbm_h10.parquet", "train (gate G1)", "Stage A OOF scores, reproduction check only"),
]


def sha(p):
    return hashlib.sha256((MODEL_DIR / p).read_bytes()).hexdigest()


rows = [dict(path=f"Model/{p}", used_by=u, purpose=w, sha256=sha(p)) for p, u, w in INPUTS]
(HERE / "results" / "inputs_manifest.json").write_text(json.dumps(rows, indent=1), encoding="utf-8")
md = ["# External inputs (read-only)", "",
      "Every file outside `studies/learning_curve/` that a script of this study reads. None is written. The dataset and "
      "label files hold all 995 users, but `05_tune.load()` drops the 136 test users' rows on load, and no test score "
      "file (`work/test/`) is read. Generated by `inputs_manifest.py`.", "", "| File | Used by | Purpose | SHA-256 |", "|---|---|---|---|"]
md += [f"| `{r['path']}` | {r['used_by']} | {r['purpose']} | `{r['sha256'][:16]}…` |" for r in rows]
(HERE / "INPUTS.md").write_text("\n".join(md) + "\n", encoding="utf-8")
print(f"{len(rows)} inputs written to INPUTS.md")
